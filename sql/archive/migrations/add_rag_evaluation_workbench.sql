USE postgrad_selector;

-- Standalone, idempotent migration for the RAG evaluation workbench.
-- Keep these definitions aligned with sql/20_ai_runtime_schema.sql.
CREATE TABLE IF NOT EXISTS rag_eval_dataset (
    id BIGINT NOT NULL AUTO_INCREMENT,
    dataset_key VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    version VARCHAR(64) NOT NULL,
    dataset_type VARCHAR(16) NOT NULL COMMENT 'DEV/FROZEN/SAFETY',
    lifecycle_state VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/READY/FROZEN',
    description VARCHAR(512) NULL,
    source_dataset_id BIGINT NULL,
    checksum_sha256 CHAR(64) NULL,
    case_count INT NOT NULL DEFAULT 0,
    lock_version INT NOT NULL DEFAULT 0,
    created_by VARCHAR(64) NOT NULL DEFAULT '',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(64) NOT NULL DEFAULT '',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_rag_eval_dataset_key_version (dataset_key, version),
    KEY idx_rag_eval_dataset_type_state (dataset_type, lifecycle_state),
    KEY idx_rag_eval_dataset_updated (updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='RAG evaluation dataset versions';

CREATE TABLE IF NOT EXISTS rag_eval_case (
    id BIGINT NOT NULL AUTO_INCREMENT,
    dataset_id BIGINT NOT NULL,
    case_key VARCHAR(96) NOT NULL,
    query_text VARCHAR(2000) NOT NULL,
    category VARCHAR(32) NULL,
    difficulty VARCHAR(16) NOT NULL DEFAULT 'medium',
    expected_metadata_json JSON NULL,
    relevant_conditions_json JSON NULL,
    relevant_sources_json JSON NULL,
    no_answer TINYINT(1) NOT NULL DEFAULT 0,
    source_data_available TINYINT(1) NOT NULL DEFAULT 1,
    expected_fallback TINYINT(1) NOT NULL DEFAULT 0,
    expected_route VARCHAR(32) NULL,
    tags_json JSON NULL,
    reviewer_note VARCHAR(1000) NULL,
    created_by VARCHAR(64) NOT NULL DEFAULT '',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(64) NOT NULL DEFAULT '',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_rag_eval_case_dataset_key (dataset_id, case_key),
    KEY idx_rag_eval_case_dataset_category (dataset_id, category),
    CONSTRAINT fk_rag_eval_case_dataset FOREIGN KEY (dataset_id) REFERENCES rag_eval_dataset(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Human-labelled RAG evaluation cases';

CREATE TABLE IF NOT EXISTS rag_eval_run (
    run_id VARCHAR(36) NOT NULL,
    dataset_id BIGINT NOT NULL,
    dataset_checksum CHAR(64) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    modes_json JSON NOT NULL,
    parameter_snapshot_json JSON NOT NULL,
    qdrant_alias VARCHAR(128) NULL,
    qdrant_collection VARCHAR(128) NULL,
    embedding_model VARCHAR(128) NULL,
    rerank_model VARCHAR(128) NULL,
    git_commit VARCHAR(64) NULL,
    total_cases INT NOT NULL DEFAULT 0,
    completed_cases INT NOT NULL DEFAULT 0,
    aggregate_metrics_json JSON NULL,
    error_code VARCHAR(64) NULL,
    error_summary VARCHAR(512) NULL,
    cancel_requested TINYINT(1) NOT NULL DEFAULT 0,
    created_by VARCHAR(64) NOT NULL DEFAULT '',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    started_at DATETIME(3) NULL,
    finished_at DATETIME(3) NULL,
    PRIMARY KEY (run_id),
    KEY idx_rag_eval_run_dataset_created (dataset_id, created_at),
    KEY idx_rag_eval_run_status_created (status, created_at),
    CONSTRAINT fk_rag_eval_run_dataset FOREIGN KEY (dataset_id) REFERENCES rag_eval_dataset(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Persistent RAG evaluation experiments';

CREATE TABLE IF NOT EXISTS rag_eval_case_result (
    id BIGINT NOT NULL AUTO_INCREMENT,
    run_id VARCHAR(36) NOT NULL,
    case_id BIGINT NOT NULL,
    eval_mode VARCHAR(32) NOT NULL,
    passed TINYINT(1) NOT NULL DEFAULT 0,
    first_relevant_rank INT NULL,
    relevant_in_top_k INT NOT NULL DEFAULT 0,
    reciprocal_rank DECIMAL(12,8) NOT NULL DEFAULT 0,
    effective_filters_json JSON NULL,
    candidate_summary_json JSON NULL,
    selected_evidence_json JSON NULL,
    latency_ms BIGINT NULL,
    failure_reason VARCHAR(64) NULL,
    technical_error_code VARCHAR(64) NULL,
    technical_error_summary VARCHAR(512) NULL,
    human_failure_category VARCHAR(64) NULL,
    reviewer_note VARCHAR(1000) NULL,
    reviewed_by VARCHAR(64) NULL,
    reviewed_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_rag_eval_result_run_case_mode (run_id, case_id, eval_mode),
    KEY idx_rag_eval_result_run_passed (run_id, passed),
    KEY idx_rag_eval_result_failure (human_failure_category, created_at),
    CONSTRAINT fk_rag_eval_result_run FOREIGN KEY (run_id) REFERENCES rag_eval_run(run_id),
    CONSTRAINT fk_rag_eval_result_case FOREIGN KEY (case_id) REFERENCES rag_eval_case(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Per-case RAG evaluation outcomes';
