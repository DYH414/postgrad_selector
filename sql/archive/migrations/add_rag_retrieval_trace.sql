CREATE TABLE IF NOT EXISTS rag_retrieval_trace (
    id BIGINT NOT NULL AUTO_INCREMENT,
    trace_id VARCHAR(36) NOT NULL,
    operation_key VARCHAR(64) NULL,
    run_id VARCHAR(64) NULL,
    retrieval_route VARCHAR(64) NULL,
    user_id BIGINT NULL,
    query_summary VARCHAR(512) NULL COMMENT '截断后的检索问题摘要',
    outcome VARCHAR(16) NULL,
    failure_stage VARCHAR(64) NULL,
    error_summary VARCHAR(512) NULL,
    retrieved_count INT NOT NULL DEFAULT 0,
    selected_count INT NOT NULL DEFAULT 0,
    top_sources_json JSON NULL,
    metadata_filters_json JSON NULL,
    fallback_used TINYINT(1) NOT NULL DEFAULT 0,
    fallback_mode VARCHAR(64) NULL,
    embedding_latency_ms BIGINT NULL,
    retrieval_latency_ms BIGINT NULL,
    rerank_latency_ms BIGINT NULL,
    total_latency_ms BIGINT NOT NULL DEFAULT 0,
    selected_chunks_summary JSON NULL COMMENT '最多5条、每条正文最多500字符的摘要',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_rag_trace_created (created_at),
    KEY idx_rag_trace_run_created (run_id, created_at),
    KEY idx_rag_trace_operation_created (operation_key, created_at),
    KEY idx_rag_trace_outcome_created (outcome, created_at),
    KEY idx_rag_trace_trace_id (trace_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='RAG 检索追踪';
